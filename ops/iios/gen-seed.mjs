#!/usr/bin/env node
// gen-seed.mjs — generate ops/iios/seed-synthetic.sql from the mock's synthetic directory
// (services/iios-mock/src/seed.ts). Run: node ops/iios/gen-seed.mjs > ops/iios/seed-synthetic.sql
//
// Synthetic/dev only. The kernel uses uuid principal ids; the mock/OGC use string ids
// (e.g. "iios-principal-admin-1"). The bridge is a DETERMINISTIC uuidv5 over a fixed
// namespace — S3b's iios-mock resolve derives the identical uuid, so this seed and the
// runtime agree without a lookup table.
import crypto from "node:crypto";

// Keep in sync with services/iios-mock/src/seed.ts (synthetic directory).
const ORG_NOVA = "00000000-0000-4000-8000-000000000001";
const ORG_LUMEN = "00000000-0000-4000-8000-000000000002";
const CENTER_D1 = "00000000-0000-4000-8000-000000000c01";
const CENTER_THU_DUC = "00000000-0000-4000-8000-000000000c02";
const CENTER_CAU_GIAY = "00000000-0000-4000-8000-000000000c03";
const CENTER_HAI_CHAU = "00000000-0000-4000-8000-000000000c04";

const ORGS = [
  { id: ORG_NOVA, role: "iios_app_o_alpha", centers: [CENTER_D1, CENTER_THU_DUC, CENTER_CAU_GIAY] },
  { id: ORG_LUMEN, role: "iios_app_o_beta", centers: [CENTER_HAI_CHAU] },
];
const MEMBERS = [
  { sub: "iios-principal-admin-1", org: ORG_NOVA, role: "admin" },
  { sub: "iios-principal-staff-1", org: ORG_NOVA, role: "staff" },
  { sub: "iios-principal-teacher-1", org: ORG_NOVA, role: "teacher" },
  { sub: "iios-principal-teacher-2", org: ORG_NOVA, role: "teacher" },
  { sub: "iios-principal-learner-1", org: ORG_NOVA, role: "learner" },
  { sub: "iios-principal-learner-2", org: ORG_NOVA, role: "learner" },
  { sub: "iios-principal-guardian-1", org: ORG_NOVA, role: "guardian" },
  { sub: "iios-principal-norole-1", org: ORG_NOVA, role: null },
  { sub: "iios-principal-staff-org2", org: ORG_LUMEN, role: "staff" },
  { sub: "iios-principal-learner-org2", org: ORG_LUMEN, role: "learner" },
];

// Fixed namespace for the mock-id → kernel-uuid mapping (shared with iios-mock S3b).
const IIOS_NS = "6f1a0b5e-2c3d-5e4f-8a9b-0c1d2e3f4a5b";
export function uuid5(name, ns = IIOS_NS) {
  const nsBytes = Buffer.from(ns.replace(/-/g, ""), "hex");
  const b = crypto.createHash("sha1").update(nsBytes).update(name, "utf8").digest().subarray(0, 16);
  b[6] = (b[6] & 0x0f) | 0x50; // version 5
  b[8] = (b[8] & 0x3f) | 0x80; // RFC 4122 variant
  const h = b.toString("hex");
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-${h.slice(12, 16)}-${h.slice(16, 20)}-${h.slice(20)}`;
}
// Deterministic uuid for a derived object (class, enrollment) within an org.
const oid = (org, kind) => uuid5(`${kind}:${org}`, IIOS_NS);

// The synthetic directory, exported so the seed test and S3b resolve share one source.
export const DIRECTORY = { ORGS, MEMBERS, ORG_NOVA, ORG_LUMEN };

export function generateSeedSql() {
const CLASS = Object.fromEntries(ORGS.map((o) => [o.id, oid(o.id, "class")]));
const q = (s) => `'${s}'`;
const out = [];
const w = (s) => out.push(s);

w(`-- seed-synthetic.sql — GENERATED by ops/iios/gen-seed.mjs. Do not edit by hand.`);
w(`-- Synthetic/dev directory for the IIOS kernel (OGC-ADR-042 / S3a). Applied as bootstrap`);
w(`-- (superuser bypasses RLS). Idempotent. Mirrors services/iios-mock/src/seed.ts.`);
w(`BEGIN;`);
w(``);
w(`-- org mapping: kernel org-login role -> the mock's organization id (deterministic).`);
for (const o of ORGS) {
  w(`UPDATE iios.org_roles SET org_id = ${q(o.id)} WHERE role_name = ${q(o.role)};`);
  w(`INSERT INTO iios.org_roles (role_name, org_id) VALUES (${q(o.role)}, ${q(o.id)}) ON CONFLICT (role_name) DO UPDATE SET org_id = EXCLUDED.org_id;`);
}
w(``);
w(`-- catalog + capabilities + purposes referenced by grants and by bind_principal.`);
w(`INSERT INTO authz.catalog_versions (version, is_current) VALUES ('cat-2', true) ON CONFLICT (version) DO NOTHING;`);
for (const cap of ["org.admin", "evidence.read"]) {
  w(`INSERT INTO authz.capabilities (catalog_version, capability, grantable) VALUES ('cat-2', ${q(cap)}, true) ON CONFLICT DO NOTHING;`);
}
// Purposes bind_principal will accept. 'ogc.platform' is the purpose iios-mock signs grants with.
for (const pz of ["ogc.platform", "progress"]) {
  w(`INSERT INTO authz.purposes (catalog_version, purpose) VALUES ('cat-2', ${q(pz)}) ON CONFLICT DO NOTHING;`);
}
w(``);
w(`-- centers + one class per org (for teacher assignments and learner enrollments).`);
for (const o of ORGS) {
  o.centers.forEach((c, i) =>
    w(`INSERT INTO app.centers (org_id, center_id, name) VALUES (${q(o.id)}, ${q(c)}, ${q("Center " + (i + 1))}) ON CONFLICT DO NOTHING;`),
  );
  w(`INSERT INTO app.classes (org_id, class_id, center_id, name) VALUES (${q(o.id)}, ${q(CLASS[o.id])}, ${q(o.centers[0])}, 'Synthetic Class') ON CONFLICT DO NOTHING;`);
}
w(``);
w(`-- principals + role-defining grants. role is derived at resolve time from which`);
w(`-- grant table a principal appears in; org.admin presence marks orgAdmin.`);
const ptype = { admin: "staff", staff: "staff", teacher: "teacher", learner: "learner", guardian: "guardian" };
let guardianLearner = null;
for (const m of MEMBERS) {
  if (m.role === null) continue; // no-role member is intentionally absent from the kernel
  const pid = uuid5(m.sub);
  const org = ORGS.find((o) => o.id === m.org);
  w(`-- ${m.sub} (${m.role})`);
  w(`INSERT INTO authz.principals (org_id, principal_id, principal_type, label) VALUES (${q(m.org)}, ${q(pid)}, ${q(ptype[m.role])}, ${q(m.sub)}) ON CONFLICT DO NOTHING;`);
  if (m.role === "admin")
    w(`INSERT INTO authz.staff_center_grants (org_id, staff_id, center_id, capability, catalog_version, valid_from) VALUES (${q(m.org)}, ${q(pid)}, NULL, 'org.admin', 'cat-2', now() - interval '1 day') ON CONFLICT DO NOTHING;`);
  else if (m.role === "staff")
    w(`INSERT INTO authz.staff_center_grants (org_id, staff_id, center_id, capability, catalog_version, valid_from) VALUES (${q(m.org)}, ${q(pid)}, ${q(org.centers[0])}, 'evidence.read', 'cat-2', now() - interval '1 day') ON CONFLICT DO NOTHING;`);
  else if (m.role === "teacher")
    w(`INSERT INTO authz.class_assignments (org_id, teacher_id, class_id, center_id, valid_from) VALUES (${q(m.org)}, ${q(pid)}, ${q(CLASS[m.org])}, ${q(org.centers[0])}, now() - interval '1 day') ON CONFLICT DO NOTHING;`);
  else if (m.role === "learner") {
    w(`INSERT INTO app.learners (org_id, learner_id, display_name, learner_code) VALUES (${q(m.org)}, ${q(pid)}, ${q(m.sub)}, ${q(m.sub.slice(-12))}) ON CONFLICT DO NOTHING;`);
    w(`INSERT INTO app.enrollments (org_id, enrollment_id, learner_id, class_id, center_id) VALUES (${q(m.org)}, ${q(oid(m.sub, "enr"))}, ${q(pid)}, ${q(CLASS[m.org])}, ${q(org.centers[0])}) ON CONFLICT DO NOTHING;`);
    guardianLearner = pid;
  } else if (m.role === "guardian")
    w(`INSERT INTO authz.guardian_links (org_id, guardian_id, learner_id, verified_at, verified_by, evidence_ref) VALUES (${q(m.org)}, ${q(pid)}, ${q(guardianLearner)}, now() - interval '1 day', ${q(uuid5("iios-principal-admin-1"))}, 'synthetic') ON CONFLICT DO NOTHING;`);
}
w(``);
w(`COMMIT;`);
  return out.join("\n") + "\n";
}

// Emit the SQL only when run directly (so importing this module just exposes the helpers).
import { fileURLToPath } from "node:url";
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  process.stdout.write(generateSeedSql());
}
